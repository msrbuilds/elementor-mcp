/**
 * Writes includes/admin/icons.php: the inner SVG markup of every icon in
 * admin-src/ui/icon-names.json, read from lucide-static (ISC licence), so the
 * PHP frame draws the same icons as the React components.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(
	path.dirname( fileURLToPath( import.meta.url ) ),
	'..'
);
const names = JSON.parse(
	readFileSync( path.join( root, 'admin-src/ui/icon-names.json' ), 'utf8' )
);
const dir = path.join( root, 'node_modules/lucide-static/icons' );

const rows = names.map( ( name ) => {
	const svg = readFileSync( path.join( dir, `${ name }.svg` ), 'utf8' );
	const inner = svg
		.replace( /<!--[\s\S]*?-->/g, '' )
		.replace( /^[\s\S]*?<svg[^>]*>/, '' )
		.replace( /<\/svg>\s*$/, '' )
		.replace( /\s+/g, ' ' )
		.trim();
	if ( ! inner || /<script|\son[a-z]+=|javascript:/i.test( inner ) ) {
		throw new Error(
			`Unexpected markup in lucide-static icon "${ name }"`
		);
	}
	const php = inner.replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" );
	return `\t'${ name }' => '${ php }',`;
} );

const file = `<?php
/**
 * Lucide icon paths (ISC licence) for the admin frame.
 * Generated by admin-build/generate-php-icons.mjs from admin-src/ui/icon-names.json. Do not edit.
 *
 * @package EMCP_Tools
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

return array(
${ rows.join( '\n' ) }
);
`;
writeFileSync( path.join( root, 'includes/admin/icons.php' ), file );
console.log( `icons.php: ${ names.length } icons` );
